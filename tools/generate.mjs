/**
 * tools/generate.mjs - the course-data pipeline. `course-registry.js` is the
 * single source of the course path: `tracks[]` gives the track + part chrome and
 * order, `lessons[]` gives the lessons in reading order. A migrated lesson's
 * display fields come from its own `content/.../meta.js`. Loaded in a Node `vm`
 * sandbox.
 *
 * Emits browser-loadable classic scripts under `generated/`:
 *   - course-data.js   : a frozen `window.CourseData` facade over an inlined data
 *                        literal (adds a stable `id` per lesson).
 *   - concept-index.js : `window.ConceptIndex` = { byConcept, byLesson, defs },
 *                        aggregated from every migrated meta.js `concepts` graph.
 *
 * For every migrated lesson it also (re)writes that lesson's `index.html` from
 * `templates/lesson.html.tmpl`, wiring the lesson's own meta.js + data.js + the
 * correct engine (or its <id>.viz.js + Prism block) and pointing every shared
 * asset at the fixed `../../../../` prefix (a migrated page lives four dirs deep).
 *
 * `--out <dir>` mirrors ALL generated output under <dir> (the two data files plus
 * each lesson's index.html at <dir>/<relPath>/index.html) and touches nothing in
 * the real tree - the drift guard uses it to diff a fresh build against commit.
 *
 * Only Node built-ins. Deterministic output (stable key order).
 */
